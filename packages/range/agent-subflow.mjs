// Четвёртый сценарий полигона: агент вызывает вложенные воркфлоу.
//
// Зачем он самый ценный. Сканер вложенные воркфлоу не разрешает: `executeWorkflow`
// и `toolWorkflow` несут `boundary: true` и дают находки `medium`/`uncertain` —
// то есть на 513 подключений инструмент честно говорит «не знаю, что там». Это
// признанный пробел проекта. Полигон отвечает на вопрос, что
// там на самом деле, и надо ли поднимать полосу.
//
// Отличие от прошлых сценариев принципиальное. Там инъекция уговаривала агента
// вызвать НЕ ТОТ инструмент: сходить на чужой хост, тронуть чужую строку. Здесь
// инструмент тот самый, штатный и разрешённый, — инъекция управляет его
// АРГУМЕНТАМИ. Снаружи вызов выглядит как обычная работа; необратимое действие
// происходит внутри под-воркфлоу, куда сканер не заглядывает.

