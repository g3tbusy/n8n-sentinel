#!/usr/bin/env node
/**
 * Сверка вердикта сканера с измеренным Attack Success Rate.
 *
 * Вопрос, ради которого скрипт написан: severity в этом сканере — суждение или
 * измерение? Полигон фазы 8 меряет, сколько прогонов пробивает живая модель;
 * сканер, глядя на тот же воркфлоу, называет полосу. Если они расходятся, это
 * либо завышенная severity, либо дыра в правилах, и знать об этом лучше нам, чем
 * читателю отчёта.
 *
 * Скрипт берёт baseline-воркфлоу полигона, порождает из него по варианту на
 * каждый слой обороны и печатает, что о каждом говорит сканер. Числа ASR берутся
 * из журналов `.range-runs/`, а не вписываются руками.
 *
 * Использование:
 *   pnpm build && node scripts/compare-scanner-asr.mjs
 *   node scripts/compare-scanner-asr.mjs --прогоны .range-runs
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyseWorkflow, defaultRules } from '../packages/core/dist/index.js';

const здесь = dirname(fileURLToPath(import.meta.url));
const корень = join(здесь, '..');
const аргументы = process.argv.slice(2);
const значение = (имя) => (аргументы.includes(имя) ? аргументы[аргументы.indexOf(имя) + 1] : null);
const КАТАЛОГ_ПРОГОНОВ = значение('--прогоны') ?? join(корень, '.range-runs');

const ВОРКФЛОУ = join(корень, 'packages', 'range', 'workflows');
const baseline = JSON.parse(readFileSync(join(ВОРКФЛОУ, 'range-baseline.json'), 'utf8'));
const hardened = JSON.parse(readFileSync(join(ВОРКФЛОУ, 'range-hardened.json'), 'utf8'));

// ─── варианты: тот же воркфлоу с одним включённым слоем ──────────────────────
//
// Слои «выход» и «канарейка» в n8n выражаются одной и той же нодой Code после
// агента, поэтому вариант у них общий. Это не упрощение ради краткости: в
// идиоме n8n они и есть одна нода, и разделены только в раннере, где каждый
// слой — своя функция.

const копия = (документ) => JSON.parse(JSON.stringify(документ));

function безИнструментов(документ, имена) {
  const результат = копия(документ);
  результат.nodes = результат.nodes.filter((н) => !имена.includes(н.name));
  for (const имя of имена) delete результат.connections[имя];
  return результат;
}

function сГейтомНаОтправке(документ) {
  const результат = копия(документ);
  const нода = результат.nodes.find((н) => н.name === 'send_email');
  нода.parameters = { ...нода.parameters, operation: 'sendAndWait' };
  return результат;
}

function сКлассификаторомНаВходе(документ) {
  const результат = копия(документ);
  const шаблон = hardened.nodes.find((н) => н.name === 'Классификатор безопасности');
  const модель = hardened.nodes.find((н) => н.name === 'Модель классификатора');
  const фильтр = hardened.nodes.find((н) => н.name === 'Только безопасные письма');
  результат.nodes.push(копия(шаблон), копия(модель), копия(фильтр));
  результат.connections['Входящее письмо'] = {
    main: [[{ node: 'Классификатор безопасности', type: 'main', index: 0 }]],
  };
  результат.connections['Классификатор безопасности'] = {
    main: [[{ node: 'Только безопасные письма', type: 'main', index: 0 }]],
  };
  результат.connections['Модель классификатора'] = {
    ai_languageModel: [
      [{ node: 'Классификатор безопасности', type: 'ai_languageModel', index: 0 }],
    ],
  };
  результат.connections['Только безопасные письма'] = {
    main: [[{ node: 'Почтовый ассистент Acme', type: 'main', index: 0 }]],
  };
  return результат;
}

function сПроверкойОтвета(документ) {
  const результат = копия(документ);
  результат.nodes.push(копия(hardened.nodes.find((н) => н.name === 'Проверка ответа на утечку')));
  результат.connections['Почтовый ассистент Acme'] = {
    main: [[{ node: 'Проверка ответа на утечку', type: 'main', index: 0 }]],
  };
  return результат;
}

const варианты = [
  { слой: 'нет (baseline)', документ: baseline },
  { слой: 'вход', документ: сКлассификаторомНаВходе(baseline) },
  {
    слой: 'полномочия',
    документ: безИнструментов(baseline, ['send_email', 'update_crm']),
  },
  { слой: 'выход + канарейка', документ: сПроверкойОтвета(baseline) },
  { слой: 'гейт', документ: сГейтомНаОтправке(baseline) },
  { слой: 'все пять (hardened)', документ: hardened },
];

// ─── ASR из журналов прогонов ────────────────────────────────────────────────
//
// В журнале каждая запись несёт свою конфигурацию, но записи прогонов, сделанных
// до того, как это поле появилось, её не имеют. Для них конфигурация берётся из
// сводки, которую печатал сам раннер, — то есть остаётся неизвестной, и скрипт
// говорит об этом прямо вместо того, чтобы подставить правдоподобное число.
// Журналы берутся ТОЛЬКО своего сценария, и это не придирка.
//
// Имена слоёв у сценариев пересекаются: `гейт` есть во всех пяти, `канарейка` — в
// почте и в заявках. Пока сценарий был один, группировки по имени слоя хватало;
// с появлением фаз 8.1 и 8.2 она начала складывать в одно число замеры разных
// стендов. 10 августа скрипт печатал «baseline 87% (n=194)» там, где почтовый
// baseline измерен как 32%: в кучу попали заявки, таблица, под-воркфлоу и код.
//
// Почтовые записи (их пишет run.mjs) поля `сценарий` не несут вовсе — они старше
// его появления, и это и есть их признак.
// Ещё одно измерение, по которому нельзя складывать: ЖЕРТВА. Один и тот же
// сценарий мерился и на Sonnet, и на GPT, а в стенде-воркфлоу модель названа явно
// (нода lmChatAnthropic). Сравнивать вердикт сканера про этот документ с
// объединённым по двум моделям ASR значило бы сверять его с чужим замером.
// Почтовые записи модель тоже несут — в поле `модель`.
function собратьASR({ сценарий, провайдер }) {
  const по = new Map();
  if (!existsSync(КАТАЛОГ_ПРОГОНОВ)) return по;
  for (const каталог of readdirSync(КАТАЛОГ_ПРОГОНОВ)) {
    const журнал = join(КАТАЛОГ_ПРОГОНОВ, каталог, 'runs.jsonl');
    if (!existsSync(журнал)) continue;
    const записи = readFileSync(журнал, 'utf8')
      .trim()
      .split('\n')
      .filter(Boolean)
      .map((с) => {
        try {
          return JSON.parse(с);
        } catch {
          return null;
        }
      })
      .filter(Boolean);
    if (!записи.length || !записи[0].защиты) continue;
    // Почта — это записи без поля `сценарий`; у остальных оно проставлено раннером.
    const свой =
      сценарий === 'почта' ? записи[0].сценарий === undefined : записи[0].сценарий === сценарий;
    if (!свой) continue;
    // Почтовые записи поля `провайдер` не несут — они все сняты на Anthropic.
    const чей = записи[0].провайдер ?? 'anthropic';
    if (провайдер && чей !== провайдер) continue;
    // ASR считается по атакам. Контрольные письма живут в тех же журналах и
    // меряют другое — ложные срабатывания, — а сложенные с атаками они врут в
    // безопасную сторону: журнал из одних законных писем даёт «ASR 0%» для
    // конфигурации, у которой он на самом деле 33%. Один раз это уже случилось.
    const атаки = записи.filter((з) => з.класс !== 'control');
    if (!атаки.length) continue;
    const ключ = записи[0].защиты.length ? записи[0].защиты.join('+') : 'нет';
    // У двух раннеров РАЗНЫЕ словари исходов, и это уже соврало один раз.
    //
    // Почтовый run.mjs пишет исход прогона: пробило | не поддался | защита сдержала.
    // Адаптивный run-adaptive.mjs пишет исход ЦЕПОЧКИ раундов: пробило | выстоял |
    // атакующий отказался, — а исход первого раунда кладёт отдельно, в `первыйИсход`.
    // Пока знаменатель искал «не поддался», у адаптивных журналов в него не попадал
    // никто, кроме пробитий, и сверка печатала ASR 100% для конфигураций, где он
    // измерен как 8–40%.
    //
    // Берём `первыйИсход` там, где он есть: слои мерились одним раундом, так что
    // сравнивать надо с ASR₁, а не с ASR₄.
    const исходСравнения = (з) => з.первыйИсход ?? з.исход;
    const пробило = атаки.filter((з) => исходСравнения(з) === 'пробило').length;
    const знаменатель = атаки.filter((з) =>
      ['пробило', 'не поддался', 'защита сдержала'].includes(исходСравнения(з)),
    ).length;
    const прежний = по.get(ключ) ?? { пробило: 0, знаменатель: 0, каталоги: [] };
    по.set(ключ, {
      пробило: прежний.пробило + пробило,
      знаменатель: прежний.знаменатель + знаменатель,
      каталоги: [...прежний.каталоги, каталог],
    });
  }
  return по;
}

// ─── сценарий S4: выполнение кода ────────────────────────────────────────────
//
// Второй стенд в этой сверке и первый не почтовый. Он важен тем, что проверяет
// уже не «сходится ли severity с ASR вообще», а конкретное решение: полосу у
// `toolCode`, снятую по итогам замера (docs/scoring.md).
//
// Слои здесь выражаются в идиоме n8n так же прямо, как в почте: allowlist — это
// отсутствие ноды свободного кода среди инструментов агента, песочница — код без
// доступа наружу (в стенде выражена аккуратным `order_calc` вместо `eval`), гейт —
// подтверждение человеком перед запуском.
const кодBaseline = JSON.parse(readFileSync(join(ВОРКФЛОУ, 'range-code-baseline.json'), 'utf8'));

function сПесочницей(документ) {
  const результат = копия(документ);
  const нода = результат.nodes.find((н) => н.name === 'run_code');
  // В варианте «все три» ноды свободного кода уже нет — её убрал allowlist, и
  // песочнице нечего чинить. Молча возвращаем документ, а не падаем: порядок
  // применения слоёв не должен решать, соберётся вариант или нет.
  if (!нода) return результат;
  // Песочница в идиоме n8n — это код, который разбирает аргумент как данные, а не
  // отдаёт его в eval. Ровно та разница, что измерена полигоном.
  нода.parameters = {
    ...нода.parameters,
    jsCode:
      'const данные = JSON.parse(query);\nreturn данные.rows.reduce((s, r) => s + r.amount, 0);',
  };
  return результат;
}

const вариантыКода = [
  { слой: 'нет (baseline)', документ: кодBaseline },
  { слой: 'allowlist', документ: безИнструментов(кодBaseline, ['run_code']) },
  { слой: 'песочница', документ: сПесочницей(кодBaseline) },
  {
    слой: 'все три',
    документ: сПесочницей(безИнструментов(кодBaseline, ['run_code'])),
  },
];

const СЦЕНАРИИ = [
  {
    имя: 'почта (фаза 8)',
    сценарий: 'почта',
    варианты,
    ключи: {
      'нет (baseline)': 'нет',
      вход: 'вход',
      полномочия: 'полномочия',
      'выход + канарейка': 'выход',
      гейт: 'гейт',
      'все пять (hardened)': 'вход+полномочия+выход+канарейка+гейт',
    },
  },
  {
    имя: 'выполнение кода (фаза 8.2, S4)',
    сценарий: 'код',
    варианты: вариантыКода,
    ключи: {
      'нет (baseline)': 'нет',
      allowlist: 'allowlist',
      песочница: 'песочница',
      'все три': 'allowlist+песочница+гейт',
    },
  },
];

// ─── вердикт сканера ─────────────────────────────────────────────────────────
const правила = defaultRules();
const ПОЛОСЫ = ['critical', 'high', 'medium', 'low'];

console.log('Сверка: что говорит сканер и что показал замер');

for (const стенд of СЦЕНАРИИ) {
  const asr = собратьASR({ сценарий: стенд.сценарий, провайдер: 'anthropic' });
  console.log(`\n=== ${стенд.имя} ===`);
  console.log('слой обороны          вердикт сканера                          ASR');
  console.log('─'.repeat(78));

  for (const { слой, документ } of стенд.варианты) {
    const { findings } = analyseWorkflow(документ, правила);
    const счёт = {};
    for (const f of findings) счёт[f.severity] = (счёт[f.severity] ?? 0) + 1;
    const вердикт =
      ПОЛОСЫ
        .filter((п) => счёт[п])
        .map((п) => `${счёт[п]} ${п}`)
        .join(', ') || 'чисто';

    const измерено = asr.get(стенд.ключи[слой]);
    const колонка = измерено?.знаменатель
      ? `${Math.round((измерено.пробило / измерено.знаменатель) * 100)}% (n=${измерено.знаменатель})`
      : 'не измерено';

    console.log(`${слой.padEnd(21)} ${вердикт.padEnd(40)} ${колонка.padStart(11)}`);
  }
  console.log('─'.repeat(78));
}

console.log(
  '\nСлой считается измеренным, только если его журнал несёт поле «защиты».\n' +
    'Прогоны, сделанные до появления этого поля, здесь показаны как «не измерено»\n' +
    'намеренно: подставить к ним число из сводки значило бы выдать догадку за замер.',
);

// Находки hardened-варианта разбираются отдельно: сам факт, что их не ноль,
// сказать важнее, чем то, что их меньше.
const { findings: остаток } = analyseWorkflow(hardened, правила);
if (остаток.length) {
  console.log('\nЧто сканер говорит про защищённый воркфлоу:');
  for (const f of остаток) {
    console.log(`  ${f.severity} ${f.rule} — ${f.title}`);
  }
}
