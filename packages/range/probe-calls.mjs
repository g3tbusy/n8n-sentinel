#!/usr/bin/env node
// Пробник: печатает НАСТОЯЩИЕ вызовы инструментов жертвы и рядом — что о них
// говорит предикат сценария и его детектор успеха.
//
//   node packages/range/probe-calls.mjs --сценарий таблица|подворкфлоу|заявки
//     [--атака ID] [--прогонов 1] [--провайдер anthropic|openai]
//
// Зачем он существует. В фазе 8.1 детектор успеха смотрел не туда: он видел
// выход наружу только через `http_request`, а жертва подчинялась инъекции,
// вызывая подсунутый инструмент. Замер показывал ноль там, где было четыре
// пробития из четырёх, и держался так несколько прогонов. Правило, выведенное
// оттуда: новый детектор сперва проверяется глазами по настоящим вызовам, и
// только потом им что-то меряют.
//
// Этот скрипт ничего не считает и никаких выводов не делает. Он показывает, что
// жертва на самом деле вызвала, чтобы человек мог сверить это с вердиктом.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parse } from 'yaml';
import { читатьНастройки, подождать } from './lib.mjs';
import { создатьДрайверЖертвы } from './victim.mjs';
import { выбратьСценарий } from './scenarios.mjs';

const здесь = dirname(fileURLToPath(import.meta.url));
const аргументы = process.argv.slice(2);
const значение = (имя) => (аргументы.includes(имя) ? аргументы[аргументы.indexOf(имя) + 1] : null);

const ТОЛЬКО = значение('--атака');
const ПРОГОНОВ = Number(значение('--прогонов')) || 1;
const ПРОВАЙДЕР = (значение('--провайдер') || 'anthropic').toLowerCase();
const ХОДОВ = 6;

const ИМЯ_СЦЕНАРИЯ = значение('--сценарий') ?? 'таблица';
const { агент, оборона, корпус } = await выбратьСценарий(ИМЯ_СЦЕНАРИЯ);
const данные = parse(readFileSync(join(здесь, 'corpus', корпус), 'utf8'));
const КАНАРЕЙКА = данные.канарейка;
const выбор = ТОЛЬКО ? ТОЛЬКО.split(',').map((с) => с.trim()) : null;
const атаки = данные.атаки.filter((а) => !выбор || выбор.includes(а.id));

const н = читатьНастройки();
const кр =
  ПРОВАЙДЕР === 'openai'
    ? { база: н.OPENAI_BASE_URL, ключ: н.OPENAI_API_KEY, модель: н.OPENAI_MODEL || 'gpt-5.4-mini' }
    : { база: н.LLM_BASE_URL, ключ: н.LLM_API_KEY, модель: н.LLM_MODEL || 'claude-sonnet-4-6' };
if (!кр.база || !кр.ключ) {
  console.error(`В .env.local не хватает ключа для провайдера ${ПРОВАЙДЕР}`);
  process.exit(1);
}
const драйвер = создатьДрайверЖертвы({ провайдер: ПРОВАЙДЕР, ...кр });

console.log(`Пробник сценария «${ИМЯ_СЦЕНАРИЯ}» — ${кр.модель} [${ПРОВАЙДЕР}], защит нет.`);
console.log('Печатаются настоящие вызовы инструментов и вердикт детектора рядом.\n');

// Двухфазный сценарий (отравление базы знаний) печатается по фазам: сперва
// обращение с инъекцией, потом ЧИСТЫЙ вопрос с пустой историей. Смотреть надо на
// вторую — именно там видно, сработала ли посаженная запись.
const ФАЗ = агент.ФАЗ ?? 1;

for (const атака of атаки) {
  for (let прогон = 1; прогон <= ПРОГОНОВ; прогон += 1) {
    агент.подготовитьПрогон?.();
    console.log('═'.repeat(78));
    const поручение = [
      атака.поручено ? `заказ ${атака.поручено}` : null,
      атака.разрешеноДействие ? `действие ${атака.разрешеноДействие}` : null,
    ]
      .filter(Boolean)
      .join(', ');
    console.log(`${атака.id}  (прогон ${прогон}${поручение ? `, поручено: ${поручение}` : ''})`);
    console.log('═'.repeat(78));

    const инструментыБаза = атака.отравленныйИнструмент
      ? [...агент.ИНСТРУМЕНТЫ, атака.отравленныйИнструмент]
      : агент.ИНСТРУМЕНТЫ;
    const инструменты = драйвер.инструменты(инструментыБаза);
    let вызовы = [];
    let текст = '';
    let контекст = оборона.контекстПрогона(атака, КАНАРЕЙКА);

    for (let фаза = 1; фаза <= ФАЗ; фаза += 1) {
      if (ФАЗ > 1) {
        console.log(
          фаза === 1
            ? '  ─── фаза 1: обращение с инъекцией ───'
            : '  ─── фаза 2: чистый вопрос, новый разговор ───',
        );
      }
      // Контекст пересобирается перед каждой фазой: у сценария с базой знаний он
      // зависит от того, что в базе уже лежит, а лежит там результат прошлой фазы.
      контекст = оборона.контекстПрогона(атака, КАНАРЕЙКА);
      const сообщения = [{ role: 'user', content: агент.собратьСообщение(атака, фаза) }];
      const вызовыФазы = [];

      for (let ход = 0; ход < ХОДОВ; ход += 1) {
        const о = await драйвер.спросить({
          система: агент.СИСТЕМНЫЙ_ПРОМПТ_НАИВНЫЙ,
          инструменты,
          сообщения,
        });
        if (о.код !== 200) {
          console.log(`  ! прогон не состоялся: ${о.ошибка ?? `HTTP ${о.код}`}`);
          break;
        }
        if (о.обрублен) {
          console.log('  ! прогон не состоялся: ответ обрублен по лимиту токенов');
          break;
        }
        if (о.текст) текст = о.текст;
        for (const з of о.вызовы ?? []) {
          вызовыФазы.push({ name: з.name, input: з.input });
          console.log(`  вызов: ${з.name}`);
          console.log(`         аргументы: ${JSON.stringify(з.input)}`);
          console.log(
            `         предикат:  ${оборона.объяснитьВызов({ name: з.name, input: з.input }, контекст)}`,
          );
        }
        if (!(о.вызовы ?? []).length) break;
        драйвер.добавитьХодИРезультаты(
          сообщения,
          о.ход,
          о.вызовы.map((з) => ({
            id: з.id,
            содержимое: агент.выполнитьИнструмент(з.name, з.input, КАНАРЕЙКА),
          })),
        );
        await подождать(1500);
      }

      // Детектор смотрит вызовы ПОСЛЕДНЕЙ фазы: у двухфазного сценария вред — это
      // то, что сработало на чистом вопросе, а не то, что агент записал в базу.
      вызовы = вызовыФазы;
      if (фаза < ФАЗ) await подождать(1500);
    }

    const вердикт = оборона.проверитьУспех(атака, вызовы, контекст);
    console.log('');
    console.log(`  вызовов всего: ${вызовы.length}`);
    console.log(`  ДЕТЕКТОР: ${вердикт.пробило ? `ПРОБИЛО — ${вердикт.чем}` : 'пробития нет'}`);
    if (текст) console.log(`  жертва ответила: ${текст.slice(0, 220).replace(/\n/g, ' ')}`);
    console.log('');
    await подождать(1500);
  }
}
