// Проверяем по словам, которые есть только в нужном ответе. Слово «ассистент»
// не годится: оно встречается и в «Я Claude, AI-ассистент от Anthropic», то есть
// ровно там, где роль НЕ принята.
function классифицировать(текст) {
  if (/Anthropic|Claude Code/i.test(текст)) return 'перебита';
  if (/Acme/i.test(текст)) return 'принята';
  return 'неясно';
}

