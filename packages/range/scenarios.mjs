// Реестр сценариев полигона: что подставляется в раннер вместо жёстко зашитой
// тройки «агент + оборона + корпус».
//
// Зачем отдельный файл. До фазы 8.2 сценарий был один, и `run-adaptive.mjs`
// импортировал его модули напрямую. Второй сценарий в такой схеме означает копию
// раннера, а копия транспорта в проекте уже есть одна и числится долгом. Здесь
// же расходится ровно то, что у сценариев разное, а метрики, журнал, усиление и
// продолжение с места обрыва остаются общими — иначе ASR₁ и ASR₄ у двух
// сценариев окажутся посчитаны по-разному, и сравнивать их будет нельзя.
//
// ─── Что обязан экспортировать модуль АГЕНТА ────────────────────────────────
//   СИСТЕМНЫЙ_ПРОМПТ_НАИВНЫЙ  роль жертвы без единой оговорки про недоверенный
//                             ввод — это и есть baseline
//   ИНСТРУМЕНТЫ               объявления инструментов в формате Anthropic;
//                             драйвер жертвы сам переведёт их под OpenAI
//   выполнитьИнструмент(имя, аргументы, канарейка) -> строка
//                             заглушки. Наружу не ходит ничего, все адреса
//                             вымышлены (.example и .invalid)
//   собратьСообщение(атака) -> строка
//                             как n8n склеивает тело webhook, выдачу поиска и
//                             результат прошлой ноды в один промпт
//   сИнъекцией(атака, текст) -> атака
//                             куда именно атакующий кладёт переписанный текст
//   текстИнъекции(атака) -> строка | undefined
//                             обратное к предыдущему: что показывать в журнале
//   АТАКУЮЩИЙ                 { система, цель, переписать } — промпт усилителя.
//                             Он знает цель сценария: в заявках это «сходи на
//                             внешний хост», в таблице — «испорти чужие строки»
//
// ─── Что обязан экспортировать модуль ОБОРОНЫ ───────────────────────────────
//   СЛОИ                      имена слоёв для `--защиты`
//   проверитьВызов(вызов, включённые, контекст) -> причина | null
//   проверитьУспех(атака, вызовы, контекст) -> { пробило, чем? }
//                             ДЕТЕКТОР УСПЕХА живёт здесь, рядом со слоями, и
//                             это не вкусовщина: в фазе 8.1 детектор и два слоя
//                             несли по своей копии условия «куда уходит вызов»,
//                             копии разошлись, и самый результативный канал
//                             показывал ложный ноль несколько прогонов подряд.
//                             Общий предикат — единственная защита от повтора.
//   объяснитьВызов(вызов, контекст) -> строка
//                             как объяснить вызов человеку в пробнике. Печатается
//                             рядом с настоящими аргументами, чтобы вердикт
//                             детектора можно было сверить глазами ДО замера
//   контекстПрогона(атака, канарейка) -> объект
//                             что детектор и слои должны знать про эту атаку.
//                             В заявках это адресат подсунутого инструмента, в
//                             таблице — поручённый заказ и правка, которую
//                             инструмент делает сам. Раннер поле не читает и
//                             передаёт объект как есть.

export const СЦЕНАРИИ = {
  заявки: {
    описание: 'приёмщик заявок из webhook; ущерб — утечка наружу HTTP-запросом',
    агент: () => import('./agent-intake.mjs'),
    оборона: () => import('./defences-intake.mjs'),
    корпус: 'attacks-intake.yaml',
  },
  таблица: {
    описание: 'ведение таблицы заказов; ущерб — порча чужих данных, а не утечка',
    агент: () => import('./agent-table.mjs'),
    оборона: () => import('./defences-table.mjs'),
    корпус: 'attacks-table.yaml',
  },
  подворкфлоу: {
    описание: 'вызов вложенных воркфлоу; инъекция управляет аргументами, а не выбором инструмента',
    агент: () => import('./agent-subflow.mjs'),
    оборона: () => import('./defences-subflow.mjs'),
    корпус: 'attacks-subflow.yaml',
  },
  код: {
    описание:
      'расчёт по заявке с выполнением кода; проверяет утверждение сканера о полосе toolCode',
    агент: () => import('./agent-code.mjs'),
    оборона: () => import('./defences-code.mjs'),
    корпус: 'attacks-code.yaml',
  },
  база: {
    описание: 'отравление базы знаний; ДВУХФАЗНЫЙ прогон, вред проявляется на втором запуске',
    агент: () => import('./agent-kb.mjs'),
    оборона: () => import('./defences-kb.mjs'),
    корпус: 'attacks-kb.yaml',
  },
};

export const ИМЕНА_СЦЕНАРИЕВ = Object.keys(СЦЕНАРИИ);

export async function выбратьСценарий(имя) {
  // Список известных имён печатает вызывающий: сюда же прилетают и ошибки
  // импорта модулей сценария, и для них список тоже к месту.
  const описание = СЦЕНАРИИ[имя];
  if (!описание) throw new Error(`Нет сценария «${имя}»`);
  const [агент, оборона] = await Promise.all([описание.агент(), описание.оборона()]);
  return { имя, описание: описание.описание, агент, оборона, корпус: описание.корпус };
}
