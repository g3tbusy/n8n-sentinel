/**
 * Всё, к чему парсер может придраться.
 *
 * Разбор никогда не бросает исключение. Прогон по корпусу трогает тысячи документов, часть
 * которых вообще не воркфлоу, и двухсотый битый файл не должен заканчивать прогон — поэтому
 * любая проблема становится предупреждением, приложенным к результату. Каждый код ниже
 * соответствует тому, что встречалось в настоящем корпусе, а не гипотезе.
 */
export type ParseWarningCode =
  /** На входе не объект или нет пригодного массива `nodes`. Разобрать не удалось ничего. */
  | 'not_a_workflow'
  /** У ноды нет пригодного `name`, поэтому сослаться на неё никто не сможет. Нода выброшена. */
  | 'node_without_name'
  /** У ноды нет `type`. Оставлена с пустым типом — фаза 2 назовёт её неизвестной. */
  | 'node_without_type'
  /** Две ноды делят имя. n8n это запрещает; побеждает первая. */
  | 'duplicate_node_name'
  /** Ключ в `connections` называет несуществующую ноду. См. docs §6.1 (мохибейк). */
  | 'unknown_connection_source'
  /** Конец связи указывает на несуществующую ноду. См. docs §6.2 (удалённая нода). */
  | 'unknown_connection_target'
  /** Слоты или концы связи оказались не той формы, которую требует формат. См. docs §6.3. */
  | 'malformed_connections'
  /** Тип связи, который не `main` и не `ai_*`. Считается потоком данных. */
  | 'unknown_connection_type';

export interface ParseWarning {
  readonly code: ParseWarningCode;
  /** Человекочитаемое и достаточно конкретное, чтобы по нему можно было действовать. */
  readonly message: string;
  /** Задействованная нода или ключ связи, если такие есть. */
  readonly at?: string;
}

export function warn(code: ParseWarningCode, message: string, at?: string): ParseWarning {
  return at === undefined ? { code, message } : { code, message, at };
}
