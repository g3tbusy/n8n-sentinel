#!/usr/bin/env node
// Замер стойкости персоны на купленном прокси — блокер фазы 8.
//
//   node scripts/measure-persona.mjs [--прогонов 10]
//
// Прокси подмешивает к каждому запросу свой системный промпт с личностью
// «я Claude Code», и в части запросов эта личность перебивает нашу. Уязвимый
// агент полигона обязан быть почтовым ассистентом стабильно, иначе таблица ASR
// померяет случайность вместо стойкости защит.
//
// Скрипт сравнивает четыре варианта постановки роли по N прогонов каждый и
// печатает долю принятых. Один прогон ничего не доказывает: роль принималась
// 2 раза из 5 при полностью одинаковом запросе.
//
// Сырьё каждого запроса пишется в .llm-probe/persona-<метка>.jsonl.

import { readFileSync, mkdirSync, appendFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const корень = join(dirname(fileURLToPath(import.meta.url)), '..');

function читатьНастройки() {
  let текст;
  try {
    текст = readFileSync(join(корень, '.env.local'), 'utf8');
  } catch {
    console.error('Нет .env.local в корне пакета.');
    process.exit(1);
  }
  const настройки = {};
  for (const строка of текст.split('\n')) {
    const m = строка.match(/^\s*([A-Z_]+)\s*=\s*(.*)$/);
    if (m) настройки[m[1]] = m[2].trim();
  }
  return настройки;
}

// Прокси всегда отвечает потоком и подмешивает хвост `data: [DONE]`.
function разобратьОтвет(тело) {
  const без = тело.replace(/\s*data:\s*\[DONE\]\s*$/, '').trim();
  try {
    return JSON.parse(без);
  } catch {
    return null;
  }
}

