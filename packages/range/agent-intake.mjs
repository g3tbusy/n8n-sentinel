// в библиотеке n8n далеко не главная: `gmailTool` стоит у 4,8% вооружённых
// агентов, а источник `gmailTrigger` даёт 4,3% находок сканера. Массовые формы
// другие: инструмент HTTP-запроса — 14,1% (`httpRequestTool` плюс
// `lc:toolHttpRequest`), запись в таблицу — около 12% (Sheets, Airtable, Notion),
// источник `webhook` — 12 525 находок против 1527 у почты.
//
// Здесь утечка устроена иначе, и это главное отличие от почтового сценария: агенту
