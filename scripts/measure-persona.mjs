const подождать = (мс) => new Promise((в) => setTimeout(в, мс));

async function прогон(вариант, номер) {
  const начало = Date.now();
  let ответ;
  let повторов = 0;
  for (;;) {
    try {
      const r = await fetch(`${БАЗА}/v1/messages`, {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'x-api-key': КЛЮЧ,
          'anthropic-version': '2023-06-01',
        },
        body: JSON.stringify({ model: МОДЕЛЬ, max_tokens: 150, ...вариант.тело }),
      });
      const текстОтвета = await r.text();
      // 429 — это «приходи через минуту», а не результат замера. Ждём и повторяем,
      // иначе лимит попадёт в таблицу под видом непринятой роли.
      if (r.status === 429 && повторов < ПОВТОРОВ_ПО_429) {
        повторов += 1;
        const заголовок = Number(r.headers.get('retry-after'));
        await подождать(
          Number.isFinite(заголовок) && заголовок > 0 ? заголовок * 1000 : 5000 * повторов,
        );
        process.stdout.write('·');
        continue;
      }
      ответ = { код: r.status, тело: разобратьОтвет(текстОтвета) };
    } catch (ошибка) {
      ответ = { код: 0, тело: null, ошибка: String(ошибка?.message ?? ошибка) };
    }
    break;
  }
  const текст = ответ.тело?.content?.find((b) => b.type === 'text')?.text ?? '';
  const исход = ответ.код === 200 && текст ? классифицировать(текст) : 'сбой';
  const запись = {
    вариант: вариант.имя,
    номер,
    исход,
    код: ответ.код,
    входныеТокены: ответ.тело?.usage?.input_tokens ?? null,
    мс: Date.now() - начало,
    текст: текст.slice(0, 300),
    повторов,
    ошибка: ответ.ошибка,
  };
  appendFileSync(журнал, JSON.stringify(запись) + '\n');
  process.stdout.write({ принята: '✓', перебита: '✗', неясно: '?', сбой: '!' }[исход] ?? '?');
  return запись;
}

// Строго по одному, с паузой между запросами: см. ПАУЗА_МС.
async function поодиночке(задачи) {
  const итог = [];
  for (const задача of задачи) {
    итог.push(await задача());
    await подождать(ПАУЗА_МС);
  }
  return итог;
}

